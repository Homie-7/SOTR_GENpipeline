"""Put a GENERATED puddle take (a close top-down patch of the oak) into the scripted Louvre floor (gallery_floor.py).

Built 2026-10-05 for S1-GAL-PUDDLE-RETURN (Homie: the puddle should "appear as if water was dropping on it and then
slowly, slowly building… hyper-real"). The take is a 3.0 x 1.69 m patch of the chosen floor plate, centred on the
spill (x 0, 1.0 m out from CENTRE), generated by Seedance from that patch (prompts/S1-GAL-PUDDLE-RETURN.txt).
Everything outside the water stays the scripted floor pixel for pixel; only the water's change is carried over:

1. ALIGN: one affine per take, take -> the reference patch, by ECC on the patch's outer ring (no water lands there).
   Seedance reframes by ~1-3% but holds it through a take (v1: identical at frame 0, middle and last). In References
   mode the plate is only a loose guide: v2 REDREW the floor (other planks), ECC finds nothing, identity is used.
2. CHANGE: ratio = aligned frame / the take's own dry frames (the mean of the first --dry-frames, before the first
   drop). 1.0 where nothing changed; darker wet wood, glints and (later) the glow where the water is.
3. MASK: where the ratio departs from 1 (blurred, dilated, feathered), accumulated over time (the water only grows,
   so the mask never flickers off between ripples); feathered to 0 at the patch border.
4. APPLY: the floor patch region of --base (the dry lit floor, or VANISH's last frame with its faint damp ghost) x
   (1 + mask * (ratio - 1)). The patch is from the same plate the floor is built from, so this is the take relit to
   the floor's light. Written as ProRes 422 HQ q2 (yuv422p10le), 24 fps, with the take's own sound (standing rule).

NOISE (2026-10-05, the dark Versailles floor): on dark oak Seedance's frame-to-frame tone shimmer is ~10x the pale oak's
   in ratio terms (v4: ~10% of DRY pixels over the old fixed 0.03; whole panels joined the pool). So every ratio is first
   divided by its own exposure drift (the median ratio on the patch's outer 8% band, where the water never reaches) and the
   threshold is max(base, 3 x the band's 95th percentile) per frame (noise_floor()). On pale oak that stays at the base.

5. --glimmer (Homie, 2026-10-05: "a glimmer on the edges… like a portal has glowing edges, but… subtle", teal): the pool's
   waterline traced per frame from the same ratio, a thin teal rim travelling slowly round it (glimmer()); --hold N keeps
   the last water frame still with the glimmer moving (loops every --loop s); --dark = the blackout floor, rim the only light.

  python tools/puddle_comp.py TAKE.mp4 --patch-geom patch_geom.json --ref REF_PATCH.png --dry FLOOR_PLATE.png
         --out OUT.mov [--size 1920x1080] [--base dry|vanish] [--dry-frames 4] [--start S] [--end S] [--ease-src S]
         [--check SHEET.jpg]
         [--glimmer --glow-start S --glow-ramp S --gain G --loop S --hold S] [--dark]
Needs numpy, opencv, Pillow, ffmpeg (and tools/gallery_floor.py beside it).
"""
